#Load Saved files
@st.cache_resource
def load_model():
  with open('model.pkl','rb') as file:
   model = pickle.load(file)
  with open('scaler.pkl','rb') as file:
   scaler = pickle.load(file)
  return model, scaler

@st.cache_data
def load_data():
  data = pd.read_csv('historical_data.csv')
  data['Date'] = pd.to_datetime(data['Date'])
  data = data.sort_values('Date').reset_index(drop=True)
  return data
model, scaler = load_model()
df = load_data()

#Generate forecast dates
last_date = df['Date'].iloc[-1]
future_dates = pd.bdate_range(
    start = last_date + BDay(1),
    periods = 30,
)

features = [
    'Year','Month','Day','DayOfWeek',
    'Close_Lag_1','Close_Lag_2','Close_Lag_3',
    'Rolling_Mean_7','Rolling_Mean_14','Rolling_Mean_30'
]

def create_forecast_features(date, history):
    feature_values = {
        "Year": date.year,
        "Month": date.month,
        "Day": date.day,
        "DayOfWeek": date.dayofweek,
        "Close_Lag_1": history[-1],
        "Close_Lag_2": history[-2],
        "Close_Lag_3": history[-3],
        "Rolling_Mean_7": np.mean(history[-7:]),
        "Rolling_Mean_14": np.mean(history[-14:]),
        "Rolling_Mean_30": np.mean(history[-30:])
    }
    return pd.DataFrame([feature_values])

history = df['Close'].tail(30).tolist()
predictions = []

for date in future_dates:
  input_features = create_forecast_features(date, history)
  input_features = input_features[features]
  input_scaled = scaler.transform(input_features)
  prediction = model.predict(input_scaled)[0]
  predictions.append(prediction)
  history.append(prediction)

#Create forecast DataFrame
forecast_df = pd.DataFrame({
    'Date':future_dates,
    'Predicted_Close':predictions
})

